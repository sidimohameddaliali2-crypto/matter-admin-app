import { test } from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import jwt from 'jsonwebtoken';
import matterRouter from './matterApi.js';
import User from '../models/User.js';
import { matterImportJobs } from '../services/matterImportJobService.js';

test('HTTP import returns 202 before work, polls saved progress and enforces staff roles and dates', async t => {
  const previous = process.env.JWT_SECRET;
  process.env.JWT_SECRET = 'synthetic-import-test-key';
  t.after(() => { if (previous === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = previous; });
  t.mock.method(User, 'findById', id => ({ select: async () => ({ _id: id, isActive: true, role: id === 'viewer' ? 'viewer' : 'dispatcher' }) }));
  const job = { id: '507f1f77bcf86cd799439011', date: '2026-11-22', status: 'queued', progress: { phase: 'queued' } };
  let enqueued = 0;
  t.mock.method(matterImportJobs, 'enqueue', async date => { enqueued++; assert.equal(date, job.date); return { ...job }; });
  t.mock.method(matterImportJobs, 'get', async id => id === job.id ? { ...job } : null);
  t.mock.method(matterImportJobs, 'latest', async date => date === job.date ? { ...job } : null);
  const app = express();
  app.use(express.json());
  app.use('/api/matter', matterRouter);
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => { server.closeAllConnections(); server.close(); });
  const base = `http://127.0.0.1:${server.address().port}/api/matter/import-deliveries`;
  const token = id => jwt.sign({ id }, process.env.JWT_SECRET, { algorithm: 'HS256' });
  const headers = { 'Content-Type': 'application/json', Authorization: `Bearer ${token('dispatcher')}` };
  assert.equal((await fetch(base, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ date: job.date }) })).status, 401);
  assert.equal((await fetch(base, { method: 'POST', headers: { ...headers, Authorization: `Bearer ${token('viewer')}` }, body: JSON.stringify({ date: job.date }) })).status, 403);
  assert.equal((await fetch(base, { method: 'POST', headers, body: JSON.stringify({ date: '2026-11-31' }) })).status, 400);
  assert.equal(enqueued, 0);
  const accepted = await fetch(base, { method: 'POST', headers, body: JSON.stringify({ date: job.date }) });
  assert.equal(accepted.status, 202);
  assert.equal((await accepted.json()).data.status, 'queued');
  job.status = 'running'; job.progress = { phase: 'checking', completed: 200, total: 354 };
  const progress = await (await fetch(`${base}/jobs/${job.id}`, { headers })).json();
  assert.equal(progress.data.progress.completed, 200);
  job.status = 'completed'; job.result = { created: 11 };
  const reloaded = await (await fetch(`${base}/status?date=${job.date}`, { headers })).json();
  assert.equal(reloaded.data.result.created, 11);
  assert.equal((await fetch(`${base}/jobs/not-an-id`, { headers })).status, 400);
  assert.equal((await fetch(`${base}/jobs/507f1f77bcf86cd799439012`, { headers })).status, 404);
  assert.equal((await fetch(`${base}/status?date=${job.date}`)).status, 401);
});
